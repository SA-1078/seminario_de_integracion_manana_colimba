print(precio_a, "-", precio_b, "=", precio_a-precio_b)
print("Multiplicacion")
print(precio_a, "*", precio_b, "=", precio_a*precio_b)
print("Potencia")
print(precio_a, "**", precio_b, "=", precio_a**precio_b)
print("Division")
print(precio_a, "/", precio_b, "=", precio_a/precio_b)
print("Division Entera")
print(precio_a, "//", precio_b, "=", precio_a//precio_b)
print("Modulo")
print(precio_a, "%", precio_b, "=", precio_a%precio_b)
